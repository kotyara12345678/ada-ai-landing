def render_context() -> str:
    """Текстовая выжимка каталога для системного промпта."""
    price_lines = "\n".join(
        f"- {item.title}: от {item.price:,} ₽ ({item.summary})".replace(",", " ")
        for item in PRICES
    )
    direction_lines = "\n".join(f"- {name}: {text}" for name, text in DIRECTIONS.items())

    plan_lines = []
    for plan in MAINTENANCE_PLANS:
        plan_lines.append(
            f"- {plan.name} — {plan.price:,} ₽/мес. Часы: {plan.hours}. Бэкапы: {plan.backups}. "
            f"Поддержка: {plan.support}.".replace(",", " ")
        )
        plan_lines.append(f"  Включено: {'; '.join(plan.includes)}.")
        plan_lines.append(f"  Ограничения: {'; '.join(plan.limits)}.")

    rules = "\n".join(f"- {rule}" for rule in RULES)

    return (
        "НАПРАВЛЕНИЯ (разработка и обслуживание):\n"
        f"{direction_lines}\n\n"
        "ПРАЙС-ЛИСТ РАЗРАБОТКИ (стоимость «от», рубли РФ):\n"
        f"{price_lines}\n\n"
        "ТАРИФЫ ТЕХНИЧЕСКОГО ОБСЛУЖИВАНИЯ (рубли РФ в месяц):\n"
        f"{chr(10).join(plan_lines)}\n\n"
        "ОГРАНИЧЕНИЯ:\n"
        f"{rules}"
    )
