export const developmentDirections = directions.filter((item) => item.group === "development");
export const maintenanceDirections = directions.filter((item) => item.group === "maintenance");

export function getDirection(slug: string): Direction | undefined {
  return directions.find((direction) => direction.slug === slug);
}

export function relatedDirections(slug: DirectionSlug): Direction[] {
  const direction = getDirection(slug);
  if (!direction) return [];
  return direction.related
    .map((relatedSlug) => getDirection(relatedSlug))
    .filter((item): item is Direction => Boolean(item));
}
